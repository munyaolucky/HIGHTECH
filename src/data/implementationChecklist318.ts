function buildAreaItems(
  prefix: string,
  specs: Array<[string, ChecklistItemStatus]>
): ChecklistItemDefinition[] {
  return specs.map(([label, defaultStatus], idx) => ({
    id: `${prefix}-${idx + 1}`,
    label,
    defaultStatus,
  }));
}

