export type ChecklistItemStatus =
  | 'completed'
  | 'in_progress'
  | 'needs_attention'
  | 'not_started';

export interface ChecklistItemDefinition {
  id: string;
  label: string;
  defaultStatus: ChecklistItemStatus;
}

export interface ChecklistAreaDefinition {
  id: string;
  number: number;
  title: string;
  shortTitle: string;
  recommendedOrder: number;
  items: ChecklistItemDefinition[];
}

