export function hasStaffPermission(permissions: string[], required?: string): boolean {
  if (!required) return true;
  return permissions.includes(required);
}

export function getStaffNavigation(role: StaffRole, permissions?: string[]): {
  roleItems: StaffNavItem[];
  sharedItems: StaffNavItem[];
} {
  const perms = permissions ?? STAFF_ACCOUNTS[role]?.permissions ?? [];
  const roleItems = (ROLE_STAFF_NAV[role] ?? []).filter((item) =>
    hasStaffPermission(perms, item.permission)
  );
  const sharedItems = SHARED_STAFF_NAV.filter((item) =>
    hasStaffPermission(perms, item.permission)
  );
  return { roleItems, sharedItems };
}

