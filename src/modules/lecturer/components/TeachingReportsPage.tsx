import React, { useCallback, useEffect, useState } from 'react';
import {
  AlertCircle,
  CheckSquare,
  Download,
  FileSpreadsheet,
  Printer,
} from 'lucide-react';
import {
  TEACHING_CHECKLIST_ITEMS,
  TEACHING_REPORT_ITEMS,
  teachingModuleApi,
  type TeachingReportResultDTO,
} from '../../../services/teachingModuleApi';

export default function TeachingReportsPage() {
  const [selectedKey, setSelectedKey] = useState<string>('daily_lesson_delivery');
  const [report, setReport] = useState<TeachingReportResultDTO | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const loadReport = useCallback(async (key: string) => {
    try {
      setLoading(true);
      setError(null);
      await teachingModuleApi.ensureLecturerSession();
      const data = await teachingModuleApi.generateReport(key);
      setReport(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unable to generate report.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    void loadReport(selectedKey);
  }, [selectedKey, loadReport]);

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div>
          <p className="text-xs font-bold uppercase tracking-wider text-[#1769AA] dark:text-blue-400">
            Official Academic Reporting &amp; Export Centre
          </p>
          <h1 className="text-xl font-bold text-[#102D50] dark:text-white mt-0.5">
            Teaching, Lesson Delivery &amp; Attendance Reports (14 Standard Reports)
          </h1>
          <p className="text-xs text-slate-600 dark:text-slate-300 mt-1">
            Inspect live database metrics and export clean CSV or print-ready PDF views with automatic medical privacy redaction.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <a
            href={teachingModuleApi.getReportCsvDownloadUrl(selectedKey)}
            download
            className="px-3.5 py-2 rounded-xl bg-[#102D50] hover:bg-[#0b203a] text-white text-xs font-semibold inline-flex items-center gap-1.5"
          >
            <Download size={14} /> Export CSV
          </a>
          <button
            type="button"
            onClick={() => window.print()}
            className="px-3.5 py-2 rounded-xl border border-slate-300 dark:border-slate-700 bg-white dark:bg-slate-800 text-slate-800 dark:text-slate-100 text-xs font-semibold inline-flex items-center gap-1.5"
          >
            <Printer size={14} /> Print / PDF
          </button>
        </div>
      </div>

      {error && (
        <div role="alert" className="rounded-xl border border-red-200 dark:border-red-800 bg-red-50 dark:bg-red-950/50 px-4 py-3 text-xs font-medium text-[#B83232] dark:text-red-300 flex items-center gap-2">
          <AlertCircle size={15} />
          <span>{error}</span>
        </div>
      )}

      {/* 14-REPORT CATALOGUE GRID */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-2.5">
        {TEACHING_REPORT_ITEMS.map((item) => {
          const active = item.key === selectedKey;
          return (
            <button
              key={item.key}
              type="button"
              onClick={() => setSelectedKey(item.key)}
              className={`p-3 rounded-xl border text-left text-xs transition-colors ${
                active
                  ? 'border-[#102D50] bg-[#102D50] text-white'
                  : 'border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 text-slate-800 dark:text-slate-100 hover:border-[#1769AA]'
              }`}
            >
              <strong className="block font-semibold">{item.title}</strong>
              <span className={`block text-[11px] mt-0.5 ${active ? 'text-blue-200' : 'text-slate-500 dark:text-slate-400'}`}>
                {item.audience}
              </span>
            </button>
          );
        })}
      </div>

      {/* REPORT DATA PREVIEW */}
      <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 overflow-hidden">
        <div className="p-4 border-b border-slate-200 dark:border-slate-800 flex flex-wrap items-center justify-between gap-2 text-xs">
          <div className="flex items-center gap-2">
            <FileSpreadsheet size={16} className="text-[#1769AA]" />
            <strong className="text-sm text-[#102D50] dark:text-white">{report?.title ?? 'Generating Report...'}</strong>
          </div>
          {report && (
            <span className="font-mono text-slate-600 dark:text-slate-300 tabular-nums">
              {report.totalRows} rows · Generated by {report.generatedBy}
            </span>
          )}
        </div>

        {loading || !report ? (
          <div className="p-8 text-center text-xs text-slate-600">Loading live report rows...</div>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="bg-slate-50 dark:bg-slate-800/80 border-b border-slate-200 dark:border-slate-800 text-slate-600 dark:text-slate-300">
                <tr>
                  {report.columns.map((col) => (
                    <th key={col} className="py-2.5 px-4 font-semibold whitespace-nowrap">
                      {col}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100 dark:divide-slate-800 tabular-nums">
                {report.rows.length === 0 ? (
                  <tr>
                    <td colSpan={report.columns.length} className="py-8 text-center text-slate-500">
                      No records matched this report scope.
                    </td>
                  </tr>
                ) : (
                  report.rows.map((row, idx) => (
                    <tr key={idx}>
                      {row.map((cell, cIdx) => (
                        <td key={cIdx} className="py-2.5 px-4 text-slate-800 dark:text-slate-200">
                          {cell}
                        </td>
                      ))}
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        )}
      </div>

      {/* IMPLEMENTATION CHECKLIST */}
      <div className="rounded-2xl border border-slate-200 dark:border-slate-800 bg-white dark:bg-slate-900 p-5 space-y-3 text-xs">
        <h2 className="text-sm font-bold text-[#102D50] dark:text-white flex items-center gap-2">
          <CheckSquare size={16} className="text-emerald-700" />
          Teaching &amp; Absence Module Master Checklist (18 / 18 Active)
        </h2>
        <div className="grid grid-cols-1 md:grid-cols-2 gap-2">
          {TEACHING_CHECKLIST_ITEMS.map((item) => (
            <div key={item} className="flex items-start gap-2 text-slate-700 dark:text-slate-200">
              <CheckSquare size={14} className="text-emerald-700 shrink-0 mt-0.5" />
              <span>{item}</span>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}
